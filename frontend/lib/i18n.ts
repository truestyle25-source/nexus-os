function resolve(tabela: Record<string, Chave>, nomePt: string, prefixo: string): string {
  const chave = tabela[nomePt] ?? `${prefixo}${slug(nomePt)}`;
  const valor = TRADUCOES[getIdioma()][chave];
  return typeof valor === 'string' ? valor : nomePt;
}

/** Traduz um item do menu a partir do nome em português. */
