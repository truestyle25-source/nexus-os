/**
 * pt-BR é a identidade: o próprio código já é o texto em português, então a
 * tabela é vazia e `t()` devolve o fallback informado pelo chamador.
 */
const TRADUCOES: Record<Idioma, Record<string, unknown>> = {
  'pt-BR': {},
  'en-US': EN,
  'es-ES': ES,
};

export type Chave = string;

/**
 * Idioma efetivo, lido direto das preferências.
 *
 * Por que ler a cada chamada em vez de guardar em variável de módulo: a aba
 * Configurações salva a preferência e dispara `nexus:prefs`; se o idioma
 * vivesse numa variável, a página poderia redesenhar ANTES de o ThemeSync
 * atualizar essa variável e continuaria exibindo português. Lendo do cache
 * (que é uma variável em memória, ver `lib/prefs`) não há ordem a respeitar,
 * e o custo continua sendo ~zero.
 */
export function getIdioma(): Idioma {
  const atual = lerPrefs().idioma;
  return atual === 'en-US' || atual === 'es-ES' ? atual : 'pt-BR';
}

/** Define o idioma gravando a preferência (dispara `nexus:prefs`). */
export function definirIdioma(novo: string): void {
  gravarPrefs({ ...lerPrefs(), idioma: novo });
}

type Valor = string | ((a: Record<string, string | number>) => string);

function aplicar(valor: Valor, args?: Record<string, string | number>): string {
  if (typeof valor === 'function') return valor(args ?? {});
  let texto = valor;
  if (args) {
    for (const [k, v] of Object.entries(args)) {
      texto = texto.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return texto;
}

/**
 * Traduz uma chave, com fallback explícito para o texto em português.
 * Nunca devolve string vazia nem "undefined" — uma tradução parcial apenas
 * mantém o português nas chaves ainda não traduzidas.
 */
export function t(chave: Chave, fallback: string, args?: Record<string, string | number>): string {
  const valor = TRADUCOES[getIdioma()][chave];
  if (valor === undefined) return fallback;
  return aplicar(valor as Valor, args);
}

function slug(nome: string): string {
  return nome
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '_');
}

